/**
 * expenseCalc.js — калькулятор поля суммы в окне расхода: «73000+33000» → 106000.
 *
 * Разрешены только цифры и + - * / ( ) . — вычисляем безопасно. Суммы в сумах
 * целые, поэтому точки/запятые между группами из трёх цифр — это разделители
 * тысяч (1.500.000, 1,500,000), а не дробь. Раньше «1.500.000» не вычислялось:
 * поле показывало «1 500 000», а сумма считалась нулём и кнопка молча не
 * нажималась (проверка владельца 2026-09-26). Ведущие нули («0500») в строгом
 * режиме — синтаксическая ошибка, их тоже убираем.
 */

/** Выражение → число (NaN, если не вычисляется). */
export const evalExpr = (raw) => {
  if (raw == null) return NaN;
  // \s в JS покрывает и неразрывный пробел (им toLocaleString делит разряды)
  let s = String(raw).replace(/\s/g, '').replace(/×/g, '*').replace(/÷/g, '/');
  // разделители тысяч: 1.500.000 / 1,500,000 → 1500000
  s = s.replace(/(?<![\d.,])\d{1,3}(?:[.,]\d{3})+(?![\d.,])/g, (m) => m.replace(/[.,]/g, ''));
  s = s.replace(/,/g, '.');
  if (!s || !/[0-9]/.test(s)) return NaN;
  if (!/^[0-9+\-*/().]+$/.test(s)) return NaN;
  // ведущие нули целых чисел: 0500 → 500 (но 0.5 не трогаем)
  s = s.replace(/(^|[^0-9.])0+(?=\d)/g, '$1');
  try {
    const val = Function(`"use strict"; return (${s});`)();
    return (typeof val === 'number' && isFinite(val)) ? val : NaN;
  } catch { return NaN; }
};

/** Есть ли арифметический оператор (ведущий минус не считается). */
export const hasOperator = (s) => /[+\-*/×÷]/.test(String(s || '').slice(1));

/** Сумма к записи: округлённое положительное значение или 0. */
export const amountOf = (raw) => {
  const v = evalExpr(raw);
  return isFinite(v) && v > 0 ? Math.round(v) : 0;
};
