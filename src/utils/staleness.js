/**
 * staleness — общая отсечка «запись протухла».
 *
 * Нужна там, где задача перестаёт быть задачей: гость давно выехал, регистрация
 * истекла месяц назад. Без такой отсечки счётчики и напоминания копят записи за
 * всю историю и перестают что-либо значить (кассиру каждый день приходит
 * «Нужна регистрация!» по гостю, которого нет уже полгода).
 *
 * Отдельный модуль без JSX — чтобы логика импортировалась в тестах на node.
 */

/** Сколько дней запись остаётся «живой» задачей после того, как срок вышел. */
export const STALE_TASK_DAYS = 30;

/**
 * true — с даты прошло больше days дней.
 * Принимает 'YYYY-MM-DD' и ISO-строку; для даты без времени берём конец дня.
 */
export const isStaleSince = (dateStr, days = STALE_TASK_DAYS, now = Date.now()) => {
  if (!dateStr) return false;
  const s = String(dateStr);
  const ms = new Date(s.includes('T') ? s : `${s.slice(0, 10)}T23:59:59`).getTime();
  if (!Number.isFinite(ms)) return false;
  return now - ms > days * 86400000;
};
